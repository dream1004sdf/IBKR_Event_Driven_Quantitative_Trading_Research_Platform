def _spec_values(args: Any, settings: Any, arg_specs: Sequence[ArgSpec]) -> list[Any]:
    values: list[Any] = []
    for spec in arg_specs:
        values.append(spec(args, settings) if callable(spec) else getattr(args, spec))
    return values


def _dispatch_direct_command(args: Any, settings: Any, commands: Mapping[str, Any]) -> bool:
    if args.command == "official-add":
        commands["command_official_add"](
            settings,
            args.news_id,
            args.source_type,
            args.source_url,
            args.title,
            args.file,
            reanalyze=not args.no_reanalyze,
        )
        return True
    spec = DIRECT_COMMANDS.get(args.command)
    if spec is None:
        return False
    function_name, include_settings, arg_specs = spec
    call_args = [_settings(args, settings)] if include_settings else []
    call_args.extend(_spec_values(args, settings, arg_specs))
    commands[function_name](*call_args)
    return True


def dispatch_command(args: Any, settings: Any, commands: Mapping[str, Any]) -> None:
    if _dispatch_direct_command(args, settings, commands):
        return
    for handler in (
        handle_live_options_command,
        handle_ibkr_broker_evidence_command,
        handle_market_evidence_command,
        handle_training_command,
        handle_news_source_command,
        handle_external_market_command,
        handle_replay_execution_command,
        handle_operating_defensive_safety_command,
        handle_dashboard_command,
    ):
        if handler(args, settings, commands):
            return

    from prediction_evaluation.cli import handle_command

    if not handle_command(args, settings):
        raise SystemExit(f"Unsupported command: {args.command}")
